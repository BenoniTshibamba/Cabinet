/* ==========================================================================
   i18n.js — Internationalisation FR/EN du Cabinet Élite Juridique.
   Chargé AVANT js/app.js (voir index.html). STRINGS contient toutes les
   chaînes visibles de l'interface ; t(key, params) les résout selon la langue
   stockée dans localStorage ('cej_lang', 'fr' par défaut). Les paramètres
   {nom} dans une chaîne sont remplacés par t('cle', { nom: valeur }).
   ========================================================================== */

const LANG_KEY = 'cej_lang';
function getLang() {
  try { return localStorage.getItem(LANG_KEY) || 'fr'; } catch { return 'fr'; }
}
function setLang(lang) {
  try { localStorage.setItem(LANG_KEY, lang); } catch {}
}
function toggleLang() {
  setLang(getLang() === 'fr' ? 'en' : 'fr');
  route();
}

